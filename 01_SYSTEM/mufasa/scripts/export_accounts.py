import os
import sys

from psycopg import sql
from sqlalchemy import create_engine, text

from scripts._environment import ROOT, load_env

ACCOUNTS = text("""
    SELECT login, password_hash, profile, student_id, id_professor, course_id, name, email, must_change_password, demo
      FROM users ORDER BY profile, login
""")
COLUMNS = ("login", "password_hash", "profile", "student_id", "id_professor", "course_id", "name", "email",
           "must_change_password", "demo")


def main() -> int:
    load_env()
    url = os.environ.get("DATABASE_URL_ADMIN")
    if not url:
        print("Set DATABASE_URL_ADMIN.", file=sys.stderr)
        return 2
    engine = create_engine(url)
    with engine.connect() as c:
        rows = c.execute(ACCOUNTS).mappings().all()
        psycopg_connection = c.connection.driver_connection
        values = [sql.SQL("({})").format(sql.SQL(", ").join(sql.Literal(l[k]) for k in COLUMNS)).as_string(psycopg_connection)
                   for l in rows]
    destination = ROOT / "database" / "initial_accounts.sql"
    destination.write_text(
        "-- MUFASA initial accounts (generated by scripts/export_accounts.py). Bcrypt hashes only.\n"
        "-- Initial passwords: database/initial_credentials.csv (hand over through a secure channel).\n"
        "-- All accounts ask for a password change and terms acceptance on first access,\n"
        "-- except the demo ones, which do not get in when ENVIRONMENT=production.\n"
        f"INSERT INTO users ({', '.join(COLUMNS)}) VALUES\n" + ",\n".join(values)
        + "\nON CONFLICT DO NOTHING;\n", encoding="utf-8")
    print(f"{len(rows)} account(s) exported to {destination}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
