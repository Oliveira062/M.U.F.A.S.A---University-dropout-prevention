import argparse
import getpass
import secrets
import sys
from urllib.parse import quote

from scripts._environment import ROOT


def _password() -> str:
    return secrets.token_urlsafe(24)


def build_env(host: str, port: int, postgres_password: str, database: str, docker: bool) -> str:
    from cryptography.fernet import Fernet
    s_api, s_chat, s_calc = _password(), _password(), _password()
    u = lambda profile, password: f"postgresql+psycopg://{profile}:{quote(password, safe='')}@{host}:{port}/{database}"
    hosts = '["localhost","127.0.0.1","api","chat"]' if docker else '["localhost","127.0.0.1"]'
    return f"""# Generated by scripts/configure.py. NEVER version or send this file.
# To change a database password, change it here and run: python -m scripts.build_database

# Connection of the database owner (only to build the database and apply migrations)
DATABASE_URL_ADMIN={u("postgres", postgres_password)}
{"POSTGRES_PASSWORD=" + postgres_password if docker else ""}

# Restricted profiles, one per service
DATABASE_URL={u("mufasa_api", s_api)}
CHAT_DATABASE_URL={u("mufasa_chat", s_chat)}
CALCULATION_DATABASE_URL={u("mufasa_calculation", s_calc)}

JWT_SECRET={secrets.token_hex(32)}
JWT_ALGORITHM=HS256
JWT_EXPIRES_MINUTES=30

# Key for the support data (psychosocial support and accessibility, encrypted in the database).
# Losing this key = losing that data. Keep a copy in a safe place.
SUPPORT_KEY={Fernet.generate_key().decode()}

ENVIRONMENT=development
FORCE_HTTPS=false
ALLOWED_HOSTS={hosts}
CORS_ORIGINS=[]
DOCS_ENABLED=true

# Addresses the dashboard uses
MUFASA_API_URL={"http://api:8000" if docker else "http://127.0.0.1:8000"}
MUFASA_CHAT_URL={"http://chat:8001" if docker else "http://127.0.0.1:8001"}

# Logs: folder and level (DEBUG, INFO, WARNING, ERROR)
MUFASA_LOG_LEVEL=INFO

# Chatbot: Groq is optional. Empty = ready answers, nothing leaves the server.
GROQ_API_KEY=
GROQ_MODEL=openai/gpt-oss-20b
CHAT_AI_CLASSIFY=false
CHAT_SERVICE_WINDOW=during the academic registrar's office hours

"""


ALLOWED_KEYS = ("GROQ_API_KEY", "GROQ_MODEL", "GROQ_TEMPERATURE", "CHAT_AI_CONVERSATION", "CHAT_AI_CLASSIFY")


def read_keys(origin) -> dict:
    keys = {}
    if not origin.exists():
        return keys
    for row in origin.read_text(encoding="utf-8-sig").splitlines():
        row = row.strip()
        if not row or row.startswith("#") or "=" not in row:
            continue
        name, _, value = row.partition("=")
        name, value = name.strip(), value.strip().strip('"').strip("'")
        if name in ALLOWED_KEYS and value:
            keys[name] = value
    return keys


def apply_keys(destination, keys: dict) -> list[str]:
    rows = destination.read_text(encoding="utf-8").splitlines()
    pending, changed = dict(keys), []
    for i, row in enumerate(rows):
        name = row.split("=", 1)[0].strip()
        if name in pending:
            new = f"{name}={pending.pop(name)}"
            if row != new:
                rows[i], changed = new, changed + [name]
    for name, value in pending.items():
        rows.append(f"{name}={value}")
        changed.append(name)
    if changed:
        destination.write_text("\n".join(rows) + "\n", encoding="utf-8")
    return changed


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--docker", action="store_true", help="database in the 'db' container of docker compose")
    ap.add_argument("--overwrite", action="store_true")
    ap.add_argument("--database", default="mufasa")
    ap.add_argument("--keys", action="store_true", help="only copies the keys from groq.env to the existing .env")
    args = ap.parse_args()
    destination = ROOT / ".env"
    if args.keys:
        if not destination.exists():
            print(".env does not exist yet: run first without --keys.")
            return 1
        changed = apply_keys(destination, read_keys(ROOT / "groq.env"))
        print("Keys updated in .env: " + ", ".join(changed) if changed else "The .env keys are already up to date.")
        return 0
    if destination.exists() and not args.overwrite:
        print(".env already exists. Use --overwrite to generate another one (then build the database again).")
        return 1
    if args.docker:
        host, port, pg_password = "db", 5432, _password()
    else:
        host = input("PostgreSQL address [localhost]: ").strip() or "localhost"
        port = int(input("Port [5432]: ").strip() or 5432)
        pg_password = getpass.getpass("Password of the postgres user (set when installing PostgreSQL): ")
        if not pg_password:
            print("Empty password: give the password of the postgres user.", file=sys.stderr)
            return 1
    destination.write_text(build_env(host, port, pg_password, args.database, args.docker), encoding="utf-8")
    apply_keys(destination, read_keys(ROOT / "groq.env"))
    try:
        destination.chmod(0o600)
    except OSError:
        pass
    print(f".env created at {destination}. Next step: python -m scripts.build_database")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
